import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const source=JSON.parse(await readFile(new URL('../data/invitation-copy.json',import.meta.url),'utf8'));
const common=['labels.saveTheDate','labels.galleryTitle','labels.calendarTitle','labels.countdownEyebrow','labels.loadMore','labels.submitAnother','labels.loadingWishes','salutation','defaultRecipient','footerThanks','rsvpThanks'];
const reviewed={
 'bride-partron':[...common,'labels.receptionInvitation','labels.weddingInvitation','eventTitle'],
 'uncle-lee':[...common,'labels.weddingInvitation'],
};
const get=(content,path)=>path.split('.').reduce((value,key)=>value[key],content);
function put(content,path,value){const keys=path.split('.');const field=keys.pop();keys.reduce((parent,key)=>parent[key],content)[field]=value;}

test('Reviewed Korean SQL updates exactly 26 approved fields, preserves every other field/locale and rolls back atomically',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
   CREATE TABLE wedding_rsvp(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,guest_name text NOT NULL,phone text,attendance text NOT NULL CHECK(attendance IN ('yes','no')),guest_count int NOT NULL DEFAULT 1 CONSTRAINT wedding_rsvp_guest_count_check CHECK(guest_count BETWEEN 1 AND 20),message text,created_at timestamptz NOT NULL DEFAULT now());
   CREATE TABLE wedding_wishes(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,guest_name text NOT NULL,message text NOT NULL,created_at timestamptz NOT NULL DEFAULT now());`);
  for(const file of ['202610290001_invitation_schema.sql','202610290002_invitation_seed.sql'])await db.exec(await readFile(new URL(`../supabase/migrations/${file}`,import.meta.url),'utf8'));
  await db.exec("UPDATE wedding_invitation_contents SET content=jsonb_set(content,'{owner_note}',to_jsonb('Preserve custom database content'::text));INSERT INTO wedding_wishes(guest_name,message) VALUES ('Fixture','Preserve wish');INSERT INTO wedding_rsvp(guest_name,attendance) VALUES ('Fixture','yes')");
  const before=(await db.query('SELECT * FROM wedding_invitation_contents ORDER BY invitation_variant_id,locale')).rows;
  const variants=(await db.query('SELECT * FROM wedding_invitation_variants ORDER BY id')).rows;
  const events=(await db.query('SELECT * FROM wedding_events ORDER BY id')).rows;
  const sql=await readFile(new URL('../supabase/manual/07_apply_reviewed_korean.sql',import.meta.url),'utf8');
  for(let run=0;run<2;run++){
   const result=await db.exec(sql);const summary=result.at(-1).rows[0].korean_review_update;
   assert.equal(summary.updated_invitations,2);assert.equal(summary.reviewed_fields,26);assert.equal(summary.all_reviewed_fields_match,true);
   assert.deepEqual(summary.by_invitation,{'bride-partron':14,'uncle-lee':12});
  }
  const after=(await db.query('SELECT * FROM wedding_invitation_contents ORDER BY invitation_variant_id,locale')).rows;
  for(const old of before){
   const updated=after.find(row=>row.invitation_variant_id===old.invitation_variant_id&&row.locale===old.locale);
   if(old.locale!=='ko'||!reviewed[old.invitation_variant_id]){assert.deepEqual(updated,old);continue;}
   const expected=structuredClone(old.content);
   const current=source.find(row=>row.variant_id===old.invitation_variant_id&&row.locale==='ko').content;
   for(const key of reviewed[old.invitation_variant_id])put(expected,key,get(current,key));
   assert.deepEqual(updated.content,expected);assert.equal(updated.review_status,'approved');
  }
  assert.deepEqual((await db.query('SELECT * FROM wedding_invitation_variants ORDER BY id')).rows,variants);
  assert.deepEqual((await db.query('SELECT * FROM wedding_events ORDER BY id')).rows,events);
  assert.equal((await db.query('SELECT count(*)::int n FROM wedding_rsvp')).rows[0].n,1);
  assert.equal((await db.query('SELECT count(*)::int n FROM wedding_wishes')).rows[0].n,1);
  await db.exec("UPDATE wedding_invitation_contents SET content=jsonb_set(content,'{salutation}',to_jsonb('Keep this on rollback'::text)) WHERE invitation_variant_id='bride-partron' AND locale='ko';UPDATE wedding_invitation_contents SET content=content #- '{labels,galleryTitle}' WHERE invitation_variant_id='uncle-lee' AND locale='ko'");
  const broken=(await db.query("SELECT * FROM wedding_invitation_contents WHERE locale='ko' ORDER BY invitation_variant_id")).rows;
  await assert.rejects(db.exec(sql),/reviewed field is missing or invalid/);await db.exec('ROLLBACK');
  assert.deepEqual((await db.query("SELECT * FROM wedding_invitation_contents WHERE locale='ko' ORDER BY invitation_variant_id")).rows,broken);
 }finally{await db.close();}
});
